"""Generate a CMake toolchain file for cross-compiling to QNX 8.0 with qcc/q++."""

ARCHES = {"aarch64le": "gcc_ntoaarch64le", "x86_64": "gcc_ntox86_64"}
PROCESSOR = {"aarch64le": "aarch64", "x86_64": "x86_64"}


def cmake_toolchain(arch="aarch64le"):
    if arch not in ARCHES:
        raise ValueError(f"arch must be one of {', '.join(ARCHES)}")
    return f"""# QNX 8.0 cross-compilation toolchain, generated by qnx-port-check
# Usage:  source <sdp>/qnxsdp-env.sh
#         cmake -B build-qnx -DCMAKE_TOOLCHAIN_FILE=qnx-{arch}.cmake
set(CMAKE_SYSTEM_NAME QNX)
set(CMAKE_SYSTEM_VERSION 8.0.0)
set(CMAKE_SYSTEM_PROCESSOR {PROCESSOR[arch]})

if(NOT DEFINED ENV{{QNX_TARGET}} OR NOT DEFINED ENV{{QNX_HOST}})
  message(FATAL_ERROR "QNX_TARGET/QNX_HOST are not set. Source qnxsdp-env.sh from your QNX SDP 8.0 first.")
endif()

set(QNX_ARCH {ARCHES[arch]})
set(CMAKE_C_COMPILER qcc)
set(CMAKE_C_COMPILER_TARGET ${{QNX_ARCH}})
set(CMAKE_CXX_COMPILER q++)
set(CMAKE_CXX_COMPILER_TARGET ${{QNX_ARCH}})
set(CMAKE_SYSROOT $ENV{{QNX_TARGET}})

set(CMAKE_FIND_ROOT_PATH $ENV{{QNX_TARGET}} $ENV{{QNX_TARGET}}/{arch})
set(CMAKE_FIND_ROOT_PATH_MODE_PROGRAM NEVER)
set(CMAKE_FIND_ROOT_PATH_MODE_LIBRARY ONLY)
set(CMAKE_FIND_ROOT_PATH_MODE_INCLUDE ONLY)
set(CMAKE_FIND_ROOT_PATH_MODE_PACKAGE ONLY)
"""
